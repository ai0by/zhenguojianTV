# -*- coding: utf-8 -*-
"""把品牌 SVG 的核心图形转成 Android VectorDrawable（启动图标前景）。

Android 的 VectorDrawable 直接支持 pathData，所以路径是**无损**转换。

刻意**不使用** aapt:attr 做渐变：`<aapt:attr>` 必须挂在某个 path 的
fillColor 上，且部分第三方启动器/低版本 WebView 渲染渐变不稳。启动图标
只有 48~192dp，渐变与纯色的观感差异极小，纯色更保险。

只导出「logo 主体」，不含白底和文字 —— adaptive icon 的前景层要留安全边距，
文字放进去会被各种启动器的圆形/水滴遮罩切掉。
"""

import re
import sys

NUM = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def solid(v):
    """取一个安全的纯色：渐变按主色近似，具名色转十六进制。"""
    if not v or v == "none":
        return None
    if v.startswith("url(#"):
        gid = v[5:-1].lower()
        if "front" in gid:
            return "#E60A15"
        if "upper" in gid:
            return "#D30012"
        if "lower" in gid:
            return "#C8101B"
        return "#D30918"
    v = v.strip()
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return "#" + h.upper()
    return {"white": "#FFFFFF", "black": "#000000"}.get(v, "#000000")


def f(v):
    s = ("%.3f" % float(v)).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def main():
    svg = open(sys.argv[1], encoding="utf-8").read()

    # 去掉 defs / mask：defs 里是渐变定义（这里不用），mask 是镂空，
    # 但 app_icon.svg 本身是「白底 + 实心路径」，不需要镂空。
    body = re.sub(r"<defs.*?</defs>", "", svg, flags=re.S)
    body = re.sub(r"<mask.*?</mask>", "", body, flags=re.S)

    vb = re.search(r'viewBox="([^"]+)"', svg)
    vw, vh = [float(v) for v in NUM.findall(vb.group(1))][2:4]

    paths = []
    for m in re.finditer(r"<path([^>]*?)/>", body):
        attrs = m.group(1)
        d = re.search(r'\sd="([^"]+)"', attrs)
        if not d:
            continue
        fill = solid((re.search(r'fill="([^"]+)"', attrs) or [None, None])[1])
        stroke_attr = re.search(r'stroke="([^"]+)"', attrs)
        stroke = solid(stroke_attr.group(1)) if stroke_attr else None
        sw = re.search(r'stroke-width="([^"]+)"', attrs)
        op = re.search(r'opacity="([^"]+)"', attrs)

        if not fill and not stroke:
            continue
        line = '  <path android:pathData="%s"' % d.group(1).strip()
        line += ' android:fillColor="%s"' % (fill or "#00000000")
        if stroke:
            line += ' android:strokeColor="%s"' % stroke
            line += ' android:strokeWidth="%s"' % f(float(sw.group(1)) if sw else 1)
        if op:
            line += ' android:fillAlpha="%s"' % f(float(op.group(1)))
        line += " />"
        paths.append(line)

    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by scripts/gen_android_icon.py —— 请勿手改。",
        "     来源 assets/brand/app_icon.svg 的 logo 主体（不含白底与文字）。",
        "     用纯色而非渐变：启动图标尺寸小，渐变观感差异可忽略，",
        "     而 aapt:attr 渐变在部分启动器上渲染不稳。 -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="%s"' % f(vw),
        '    android:viewportHeight="%s">' % f(vh),
    ]
    out.extend(paths)
    out.append("</vector>")
    print("\n".join(out))


if __name__ == "__main__":
    main()
