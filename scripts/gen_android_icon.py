# -*- coding: utf-8 -*-
"""把品牌 SVG 的 logo 主体转成 Android VectorDrawable（启动图标前景）。

Android 的 VectorDrawable 直接支持 pathData，所以路径是**无损**转换。

两个坑，都是 0.8.26 才修对的：

1. **自适应图标只保证中心 72dp 可见。** 图层是 108dp，启动器会按圆形 / 水滴 /
   方形圆角去裁，只有中心 72dp（= viewport 的 66.7%）是安全区。上一版把整幅
   1024 构图（logo 顶到 y=85、底部波形铺到 y=1024）原样塞进图层，结果就是
   "logo 明显偏大、上沿被切、底部波形只剩一条红边"。现在只导出 logo 主体，
   按包围盒等比缩放后居中，对角线控制在安全区圆的 94%。

2. **只有 logo 主体。** 「真果鉴TV」字样与底部波形都是按整幅方图排的版：
   缩进安全区后，48dp 时每个字只剩 3~4 像素，糊成一团灰；波形则会在白色
   背景中间断出一条硬边（它的成立前提是贴着画布下沿）。两者都留给
   `app_icon.svg` 原稿，不进启动图标。

刻意**不使用** aapt:attr 做渐变：`<aapt:attr>` 必须挂在某个 path 的
fillColor 上，且部分第三方启动器/低版本 WebView 渲染渐变不稳。启动图标
只有 48~192dp，渐变与纯色的观感差异极小，纯色更保险。
"""

import re
import sys

NUM = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")
MARK_GROUP = re.compile(r'<g\s+id="mark"[^>]*>(.*?)</g>', re.S)

# 图层 108dp 里只有中心 72dp 是安全区；内容对角线占安全区圆的多少。
SAFE_RATIO = 0.94
LAYER_DP = 108.0
SAFE_DP = 72.0


def solid(v):
    """取一个安全的纯色：渐变按主色近似，具名色转十六进制。"""
    if not v or v == "none":
        return None
    if v.startswith("url(#"):
        gid = v[5:-1].lower()
        if "front" in gid:
            return "#E60A15"
        if "upper" in gid:
            return "#D30012"
        if "lower" in gid:
            return "#C8101B"
        return "#D30918"
    v = v.strip()
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return "#" + h.upper()
    return {"white": "#FFFFFF", "black": "#000000"}.get(v, "#000000")


def f(v):
    s = ("%.3f" % float(v)).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def path_points(d):
    """把 pathData 里的数字按两两一组当作坐标点。

    logo 只用到 M / L / C / Q / Z（全部是成对坐标），没有 H / V / A，
    所以这样取样是安全的。控制点会让包围盒略大于真实曲线 —— 对"留边距"
    这件事来说是保守方向，正好。
    """
    nums = [float(v) for v in NUM.findall(d)]
    return list(zip(nums[0::2], nums[1::2]))


def main():
    svg = open(sys.argv[1], encoding="utf-8").read()

    mark = MARK_GROUP.search(svg)
    if mark is None:
        sys.exit('app_icon.svg 里找不到 <g id="mark"> —— 图标主体无法定位')
    group = mark.group(1)

    entries = []
    for m in re.finditer(r"<path([^>]*?)/>", group):
        attrs = m.group(1)
        d = re.search(r'\sd="([^"]+)"', attrs)
        if not d:
            continue
        fill = solid((re.search(r'fill="([^"]+)"', attrs) or [None, None])[1])
        stroke_attr = re.search(r'stroke="([^"]+)"', attrs)
        stroke = solid(stroke_attr.group(1)) if stroke_attr else None
        sw = re.search(r'stroke-width="([^"]+)"', attrs)
        op = re.search(r'opacity="([^"]+)"', attrs)

        if not fill and not stroke:
            continue
        entries.append((d.group(1).strip(), fill, stroke, sw, op))

    if not entries:
        sys.exit("logo 主体里没有可用的 path")

    # 内容包围盒（含描边宽度的一点点余量），用来算居中与缩放。
    xs, ys = [], []
    for d, _, stroke, sw, _ in entries:
        pad = (float(sw.group(1)) if (stroke and sw) else 0.0) / 2.0
        for x, y in path_points(d):
            xs += [x - pad, x + pad]
            ys += [y - pad, y + pad]
    left, right, top, bottom = min(xs), max(xs), min(ys), max(ys)
    width, height = right - left, bottom - top

    vb = re.search(r'viewBox="([^"]+)"', svg)
    vw, vh = [float(v) for v in NUM.findall(vb.group(1))][2:4]

    # 安全区圆的直径（换算回 viewport 单位），再按对角线定缩放比。
    safe_diameter = min(vw, vh) * SAFE_DP / LAYER_DP
    diagonal = (width ** 2 + height ** 2) ** 0.5
    scale = SAFE_RATIO * safe_diameter / diagonal

    cx, cy = (left + right) / 2.0, (top + bottom) / 2.0
    tx = vw / 2.0 - cx * scale
    ty = vh / 2.0 - cy * scale

    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by scripts/gen_android_icon.py —— 请勿手改。",
        "     来源 assets/brand/app_icon.svg 的 <g id=\"mark\"> 主体（不含白底、",
        "     中文字样与底部波形）。",
        f"     自适应图标图层 {f(LAYER_DP)}dp 里只有中心 {f(SAFE_DP)}dp 可见，",
        "     所以这里把 logo 按包围盒等比缩小并居中，",
        f"     内容对角线 = 安全区圆的 {int(SAFE_RATIO * 100)}%：",
        f"     原始包围盒 {f(width)}x{f(height)}，缩放 {f(scale)}。",
        "     用纯色而非渐变：启动图标尺寸小，渐变观感差异可忽略，",
        "     而 aapt:attr 渐变在部分启动器上渲染不稳。 -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="%s"' % f(vw),
        '    android:viewportHeight="%s">' % f(vh),
        '  <group android:scaleX="%s" android:scaleY="%s"'
        % (f(scale), f(scale)),
        '      android:translateX="%s" android:translateY="%s">' % (f(tx), f(ty)),
    ]
    for d, fill, stroke, sw, op in entries:
        line = '    <path android:pathData="%s"' % d
        line += ' android:fillColor="%s"' % (fill or "#00000000")
        if stroke:
            line += ' android:strokeColor="%s"' % stroke
            line += ' android:strokeWidth="%s"' % f(float(sw.group(1)) if sw else 1)
        if op:
            line += ' android:fillAlpha="%s"' % f(float(op.group(1)))
        line += " />"
        out.append(line)
    out.append("  </group>")
    out.append("</vector>")
    print("\n".join(out))


if __name__ == "__main__":
    main()
